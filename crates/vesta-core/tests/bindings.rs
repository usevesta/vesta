//! Exports the TypeScript bindings to `TS_RS_EXPORT_DIR`
//! (`web/src/api/generated/`, set in `.cargo/config.toml`) and writes an
//! `index.ts` barrel. Run with `cargo test -p vesta-core`.
//!
//! `HubConfig` is intentionally absent: it carries driver secrets and never
//! reaches a client.

// Integration-test crate: helpers outside #[test] fns may panic too.
#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::error::Error;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use ts_rs::{Config, TS};
use vesta_core::{CapabilityKind, CapabilityState, ClientMessage, Dashboard, ServerMessage};

const TS_RS_HEADER: &str = "// This file was generated by [ts-rs]";
const INDEX_FILE: &str = "index.ts";
const INDEX_HEADER: &str = "// Generated by `cargo test -p vesta-core` (crates/vesta-core/tests/bindings.rs). Do not edit.\n// API types are defined once in Rust (crates/vesta-core) and exported with ts-rs.\n\n";

fn ts_files(dir: &Path, out: &mut Vec<PathBuf>) -> io::Result<()> {
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            ts_files(&path, out)?;
        } else if path.extension().is_some_and(|ext| ext == "ts") {
            out.push(path);
        }
    }
    Ok(())
}

/// Drops `//` and `/* */` comments so English prose in doc comments cannot
/// trip the `any` check.
fn strip_comments(source: &str) -> String {
    let mut code = String::new();
    let mut rest = source;
    while !rest.is_empty() {
        if let Some(after) = rest.strip_prefix("/*") {
            rest = after.find("*/").map_or("", |end| &after[end + 2..]);
        } else if let Some(after) = rest.strip_prefix("//") {
            rest = after.find('\n').map_or("", |end| &after[end..]);
        } else {
            let mut chars = rest.chars();
            if let Some(c) = chars.next() {
                code.push(c);
            }
            rest = chars.as_str();
        }
    }
    code
}

fn mentions_any(source: &str) -> bool {
    strip_comments(source)
        .split(|c: char| !(c.is_ascii_alphanumeric() || c == '_' || c == '$'))
        .any(|token| token == "any")
}

#[test]
fn export_typescript_bindings() -> Result<(), Box<dyn Error>> {
    let cfg = Config::from_env();
    let dir = cfg.out_dir().to_path_buf();

    // Remove stale ts-rs output (e.g. renamed types). Only files carrying the
    // ts-rs header are touched.
    if dir.exists() {
        let mut existing = Vec::new();
        ts_files(&dir, &mut existing)?;
        for file in existing {
            if fs::read_to_string(&file)?.starts_with(TS_RS_HEADER) {
                fs::remove_file(&file)?;
            }
        }
    }

    ServerMessage::export_all(&cfg)?;
    ClientMessage::export_all(&cfg)?;
    Dashboard::export_all(&cfg)?;
    CapabilityKind::export_all(&cfg)?;
    CapabilityState::export_all(&cfg)?;

    let mut files = Vec::new();
    ts_files(&dir, &mut files)?;
    files.retain(|file| file.file_name().is_none_or(|name| name != INDEX_FILE));
    files.sort();

    let mut index = String::from(INDEX_HEADER);
    for file in &files {
        let module = file.strip_prefix(&dir)?.with_extension("");
        let module = module
            .components()
            .map(|c| c.as_os_str().to_string_lossy())
            .collect::<Vec<_>>()
            .join("/");
        index.push_str(&format!("export type * from \"./{module}\";\n"));

        let source = fs::read_to_string(file)?;
        assert!(!mentions_any(&source), "`any` in {}", file.display());
    }
    fs::write(dir.join(INDEX_FILE), index)?;

    for expected in [
        "ServerMessage.ts",
        "ClientMessage.ts",
        "Command.ts",
        "CommandRequest.ts",
        "CommandResult.ts",
        "CommandError.ts",
        "Device.ts",
        "Endpoint.ts",
        "EndpointType.ts",
        "Capabilities.ts",
        "CapabilityState.ts",
        "CapabilityKind.ts",
        "EndpointEvent.ts",
        "Dashboard.ts",
        "Widget.ts",
        "Target.ts",
    ] {
        assert!(dir.join(expected).exists(), "missing binding {expected}");
    }
    for secret_bearing in ["HubConfig.ts", "DeviceConfig.ts", "NotificationsConfig.ts"] {
        assert!(
            !dir.join(secret_bearing).exists(),
            "{secret_bearing} must never be exported to clients"
        );
    }
    Ok(())
}

#[test]
fn any_detection() {
    assert!(mentions_any("export type X = any;"));
    assert!(mentions_any("export type X = Array<any>;"));
    assert!(!mentions_any(
        "/** Anyone, any time. */ export type X = string;"
    ));
    assert!(!mentions_any(
        "// any\nexport type Company = { many: number };"
    ));
}
